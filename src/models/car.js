// ---------- side profile of the lower body (with wheel arches) ----------
function arch(cx, r, from, to, n = 10) {
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const a = from + ((to - from) * i) / n;
    pts.push([+(cx + Math.cos(a) * r).toFixed(3), +(WY + Math.sin(a) * r).toFixed(3)]);
  }
  return pts;
}
