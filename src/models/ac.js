/** One slab of a fin-and-tube coil (fins thin in X, tubes along X), tilted by `a` about X. */
function coilSlab(cy, cz, L, a, nTubes, finMat) {
  const dy = Math.cos(a);
  const dz = Math.sin(a);
  const step = L / nTubes;
  const t0 = -L / 2 + step / 2;
  return [
    { type: 'box', size: [0.0012, L, 0.024], rotation: [a, 0, 0], position: [-0.395, cy, cz],
      array: { count: 70, offset: [0.0114, 0, 0] }, material: finMat },
    { type: 'cylinder', radius: 0.0042, height: 0.82, segments: 10, rotation: ALONG_X,
      position: [0, cy + t0 * dy, cz + t0 * dz], array: { count: nTubes, offset: [0, step * dy, step * dz] }, material: COPPER },
    { type: 'box', size: [0.004, L, 0.028], rotation: [a, 0, 0], position: [-0.403, cy, cz],
      array: { count: 2, offset: [0.806, 0, 0] }, material: M.metal('#a7adb4') },
  ];
}

